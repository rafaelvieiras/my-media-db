import {
  mkdirSync,
  mkdtempSync,
  renameSync,
  rmSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { expect, test } from "../fixtures";
import { resetBiblioteca } from "../lib/reset";

// Block F: LIBRARY (datasource + scan) and CURATION (review of drafts / orphans)
// journeys. The binary validates the datasource path on disk and scans REAL files,
// so each test seeds a temporary folder under /tmp
// (through node:fs, in the test process itself — the binary reads the same /tmp) with the
// files that produce the desired scenario:
//   - purely technical name ("2160p.mkv") -> empty Title, no id -> DRAFT (review)
//   - parseable name ("The Matrix (1999).mkv") -> auto 'cataloged' entity; deleting the
//     file + rescan leaves the entity orphan (all media_file 'missing').
//
// The scan is ASYNCHRONOUS (POST 202 + polling GET .../scan). To avoid depending on
// the timing of the front-end polling, we trigger the scan through the UI (covers DatasourceList) and
// wait for COMPLETION through `expect.poll` against the API of the target queue (web-first,
// no sleep). resetBiblioteca clears ENTITIES, but not datasources nor /tmp: each
// test clears the datasources (API) in beforeEach and removes its folders in afterEach.

// Temporary folders created in the test, removed in afterEach.
const pastas: string[] = [];

// semeiaPasta creates a unique folder under /tmp (name generated by the OS, no Date.now) and
// writes the requested files with some content (the scanner hashes the file).
function semeiaPasta(arquivos: string[]): string {
  const dir = mkdtempSync(join(tmpdir(), "mmdb-e2e-"));
  pastas.push(dir);
  for (const nome of arquivos) {
    writeFileSync(join(dir, nome), Buffer.alloc(2048, 7));
  }
  return dir;
}

// limparDatasources removes all datasources through the API (the reset does not touch them).
async function limparDatasources(
  request: import("@playwright/test").APIRequestContext,
) {
  const res = await request.get("/api/v1/library");
  const body = await res.json();
  for (const s of body.items ?? []) {
    await request.delete(`/api/v1/library/${s.id}`);
  }
}

test.beforeEach(async ({ request }) => {
  await resetBiblioteca(request);
  await limparDatasources(request);
});

test.afterEach(() => {
  for (const dir of pastas.splice(0)) {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("add and remove a datasource", async ({ page }) => {
  const dir = semeiaPasta(["1080p.mkv"]);

  await page.goto("/dashboard/library");
  await expect(
    page.getByRole("heading", { level: 1, name: "Libraries" }),
  ).toBeVisible();

  // Adding left the inline form: it navigates to the dedicated route /dashboard/library/new,
  // types the path straight into the field (without opening the PathBrowser,
  // which is just an optional visual shortcut) and chooses the type (Filmes is already the default).
  await page.getByRole("link", { name: "Add datasource" }).click();
  await expect(
    page.getByRole("heading", { level: 1, name: "Add datasource" }),
  ).toBeVisible();
  await page.getByLabel("Datasource path").fill(dir);
  // Enrichment retry override: optional, it overrides
  // the global throttle (default 15 days) only for this library.
  await page
    .getByLabel("Datasource enrichment retry (days)")
    .fill("20");
  await page.getByRole("button", { name: "Add datasource" }).click();

  // Goes back to /dashboard/library; the row appears with the path and the online state; the scan button
  // stays available.
  await expect(page).toHaveURL("/dashboard/library");
  await expect(page.getByText(dir)).toBeVisible();
  await expect(page.getByText("online")).toBeVisible();
  await expect(page.getByRole("button", { name: "Scan" })).toBeEnabled();

  // Removes it: navigates through the row to /dashboard/library/$id/edit, uses the "Danger zone" with
  // EXPLICIT 2-step confirmation (there is no direct removal anymore).
  await page.getByRole("link", { name: "Edit" }).click();
  await expect(
    page.getByRole("heading", { level: 1, name: "Edit datasource" }),
  ).toBeVisible();
  // The retry override saved on creation pre-loads here.
  const inputReentativa = page.getByLabel(
    "Datasource enrichment retry (days)",
  );
  await expect(inputReentativa).toHaveValue("20");

  // Edit the override and save (a partial PATCH only sends the field if it was "touched" --
  // it exercises that branch, distinct from the path-only one of the rescan journey).
  await inputReentativa.fill("45");
  await page.getByRole("button", { name: "Save" }).click();
  await expect(page).toHaveURL("/dashboard/library");

  // Reopens the edit form: the new value persisted through the PATCH.
  await page.getByRole("link", { name: "Edit" }).click();
  await expect(
    page.getByRole("heading", { level: 1, name: "Edit datasource" }),
  ).toBeVisible();
  await expect(
    page.getByLabel("Datasource enrichment retry (days)"),
  ).toHaveValue("45");

  // The confirmation is the shared `AlertDialog` (2-step): the dialog takes its
  // accessible name from its title ("Remove datasource", the same verb of the
  // trigger) and the removal only happens on the action INSIDE it.
  await page.getByRole("button", { name: "Remove datasource" }).click();
  const dialogo = page.getByRole("alertdialog", { name: "Remove datasource" });
  await expect(dialogo).toBeVisible();
  await expect(dialogo).toContainText("Are you sure?");
  await dialogo.getByRole("button", { name: "Confirm removal" }).click();

  // Goes back to /dashboard/library; the list is empty again.
  await expect(page).toHaveURL("/dashboard/library");
  await expect(page.getByText("No datasource registered")).toBeVisible();
});

test("scan of an unidentified file becomes a draft and the correction takes it out of the review", async ({
  page,
  request,
}) => {
  // "2160p" is only a technical token: empty Title, no external id -> DRAFT on the scan.
  const dir = semeiaPasta(["2160p.mkv"]);

  await page.goto("/dashboard/library");
  await page.getByRole("link", { name: "Add datasource" }).click();
  await page.getByLabel("Datasource path").fill(dir);
  await page.getByRole("button", { name: "Add datasource" }).click();
  await expect(page).toHaveURL("/dashboard/library");
  await expect(page.getByText(dir)).toBeVisible();

  // Triggers the scan through the UI and waits for it to PRODUCE the draft (review queue != empty).
  await page.getByRole("button", { name: "Scan" }).click();
  await expect
    .poll(
      async () => (await (await request.get("/api/v1/review")).json()).length,
      {
        timeout: 20_000,
      },
    )
    .toBeGreaterThan(0);

  // In the review screen, the draft appears as "not identified".
  await page.goto("/dashboard/review");
  await expect(
    page.getByRole("heading", { level: 1, name: "Review" }),
  ).toBeVisible();
  // The queue opens GROUPED — the reason appears in the summary of the section.
  await expect(page.getByText(/not identified/).first()).toBeVisible();

  // Opens the section (group) and then the row of the item: the preview/actions only exist open.
  // data-testid (and not a loose aria-expanded): the navbar dropdown is also a
  // button with aria-expanded and would come first in the DOM.
  await page.getByTestId("review-grupo").first().click();
  await page.getByTestId("review-linha").first().click();

  // Fix: expands the panel, searches "matrix" (fake external source) and uses the 1st one.
  await page.getByRole("button", { name: "Correct" }).click();
  await page.getByLabel("Search for the correct title").fill("matrix");
  await page.getByRole("button", { name: "Use this" }).first().click();

  // Re-enriched and re-resolved, the item leaves the queue -> empty review screen.
  await expect(page.getByText("Nothing to review")).toBeVisible();
});

test("a cataloged file that disappears becomes an orphan and can be purged", async ({
  page,
  request,
}) => {
  // Parseable name -> auto 'cataloged' entity with the file 'present'.
  const dir = semeiaPasta(["The Matrix (1999).mkv"]);

  await page.goto("/dashboard/library");
  await page.getByRole("link", { name: "Add datasource" }).click();
  await page.getByLabel("Datasource path").fill(dir);
  await page.getByRole("button", { name: "Add datasource" }).click();
  await expect(page).toHaveURL("/dashboard/library");
  await expect(page.getByText(dir)).toBeVisible();

  // 1st scan: waits for the cataloged entity to appear.
  const botaoEscanear = page.getByRole("button", { name: "Scan" });
  await botaoEscanear.click();
  await expect
    .poll(
      async () => {
        const body = await (
          await request.get("/api/v1/entities?limit=1000")
        ).json();
        const itens: Array<{ title: string }> = body.items ?? body ?? [];
        return itens.some((e) => e.title === "The Matrix");
      },
      { timeout: 20_000 },
    )
    .toBe(true);

  // The file disappears from disk; the rescan marks the media_file 'missing' -> the entity
  // (auto-created, without an owner edit) becomes orphan.
  unlinkSync(join(dir, "The Matrix (1999).mkv"));
  await expect(botaoEscanear).toBeEnabled();
  await botaoEscanear.click();
  await expect
    .poll(
      async () => (await (await request.get("/api/v1/orphans")).json()).length,
      {
        timeout: 20_000,
      },
    )
    .toBeGreaterThan(0);

  // On the orphans screen, purges with EXPLICIT 2-step confirmation.
  await page.goto("/dashboard/orphans");
  await expect(
    page.getByRole("heading", { level: 1, name: "Orphans" }),
  ).toBeVisible();
  await expect(page.getByRole("link", { name: "The Matrix" })).toBeVisible();

  await page.getByRole("button", { name: "Purge The Matrix" }).click();
  const dialogo = page.getByRole("alertdialog", { name: "Confirm purge" });
  await expect(dialogo).toBeVisible();
  await dialogo.getByRole("button", { name: "Confirm purge" }).click();

  // Purged: the queue is empty.
  await expect(page.getByText("No orphans")).toBeVisible();
});

test("editing the path of a registered datasource rescans without a new scan", async ({
  page,
  request,
}) => {
  // Seeds it with a catalogable file to prove that the rescanned media_file
  // keeps resolving the same entity, WITHOUT triggering a scan.
  const dirAntigo = semeiaPasta(["The Matrix (1999).mkv"]);

  await page.goto("/dashboard/library");
  await page.getByRole("link", { name: "Add datasource" }).click();
  await page.getByLabel("Datasource path").fill(dirAntigo);
  await page.getByRole("button", { name: "Add datasource" }).click();
  await expect(page).toHaveURL("/dashboard/library");
  await expect(page.getByText(dirAntigo)).toBeVisible();

  // 1st scan: the cataloged entity appears.
  await page.getByRole("button", { name: "Scan" }).click();
  await expect
    .poll(
      async () => {
        const body = await (
          await request.get("/api/v1/entities?limit=1000")
        ).json();
        const itens: Array<{ title: string }> = body.items ?? body ?? [];
        return itens.some((e) => e.title === "The Matrix");
      },
      { timeout: 20_000 },
    )
    .toBe(true);

  // The disk "moves": renames the physical folder to a new path
  // (same content, new mount) and edits the datasource to point there --
  // WITHOUT running the scan again.
  const dirNovo = `${dirAntigo}-remontado`;
  renameSync(dirAntigo, dirNovo);
  pastas.splice(pastas.indexOf(dirAntigo), 1, dirNovo);

  // Edit left the list (pencil icon with an inline form) for the dedicated route
  // /dashboard/library/$id/edit.
  await page.getByRole("link", { name: "Edit" }).click();
  await expect(
    page.getByRole("heading", { level: 1, name: "Edit datasource" }),
  ).toBeVisible();
  await page.getByLabel("Datasource path").fill(dirNovo);
  await page.getByRole("button", { name: "Save" }).click();

  // Goes back to /dashboard/library; the row now shows the new path, online, without
  // needing a scan -- the link with the already cataloged entity remains intact.
  await expect(page).toHaveURL("/dashboard/library");
  await expect(page.getByText(dirNovo)).toBeVisible();
  await expect(page.getByText("online")).toBeVisible();
  await page.goto("/");
  await expect(
    page.getByRole("link", { name: /Matrix/ }).first(),
  ).toBeVisible();

  // "View all" (ADR-0030): link next to the carousel title,
  // it only appears with real data in the rail (this item IS owned, through the real scan above)
  // — it navigates to /library/movies, the complete listing of that type.
  await page.getByRole("link", { name: "View all" }).click();
  await expect(page).toHaveURL("/library/movies");
  await expect(
    page.getByRole("link", { name: /Matrix/ }).first(),
  ).toBeVisible();
});

test("a file with a number outside the external tree becomes a provisional episode", async ({
  request,
}) => {
  // The fake provider tree has S01E01..E03; the S01E99 file
  // does not exist there. Before, it ended up without an episode (no NFO, no synopsis in the
  // consuming library); now a provisional episode is born in the right season,
  // with the title pattern of the enrichment.
  const dir = mkdtempSync(join(tmpdir(), "mmdb-e2e-serie-"));
  pastas.push(dir);
  mkdirSync(join(dir, "Springfield Tales", "Season 01"), { recursive: true });
  writeFileSync(
    join(dir, "Springfield Tales", "Season 01", "Springfield Tales S01E99.mkv"),
    Buffer.alloc(2048, 7),
  );

  const res = await request.post("/api/v1/library", {
    data: { path: dir, type: "tv", content_type: "series" },
  });
  expect(res.status()).toBe(201);
  const ds = await res.json();

  expect((await request.post(`/api/v1/library/${ds.id}/scan`)).status()).toBe(
    202,
  );
  await expect
    .poll(
      async () =>
        (await (await request.get(`/api/v1/library/${ds.id}/scan`)).json())
          .running,
      { timeout: 30_000 },
    )
    .toBe(false);

  // The series was imported from the fake provider and the provisional episode is in
  // its tree, in season 1, with the title pattern of the enrichment.
  // (/api/v1/entities lists works: the episode is read through the series tree.)
  const series = await (
    await request.get("/api/v1/entities?type=tv&limit=20")
  ).json();
  const serie = (series.items ?? []).find((e: { title?: string }) =>
    (e.title ?? "").includes("Springfield"),
  );
  expect(serie).toBeTruthy();
  const arvore = await (
    await request.get(`/api/v1/entities/${serie.id}/episodes`)
  ).json();
  const titulos = (arvore.groups ?? []).flatMap(
    (g: { episodes?: { title?: string }[] }) =>
      (g.episodes ?? []).map((e) => e.title),
  );
  expect(titulos).toContain("Episódio 99");
});
